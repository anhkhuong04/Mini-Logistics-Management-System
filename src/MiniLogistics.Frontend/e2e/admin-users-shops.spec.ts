import { expect, test } from '@playwright/test';
import { adminLogin, confirmAdmin } from './admin-helpers';
test.skip(!process.env.MINILOGISTICS_E2E_IDENTITY_FIXTURE, 'Requires isolated Identity/Application fixture.');
test('Admin creates internal user, changes capacity, password and Shop activity with confirmation', async ({ page }) => {
  test.setTimeout(90000);
  await adminLogin(page, '/admin/users');
  const form = page.locator('form').filter({ has: page.getByRole('textbox', { name: 'Họ tên', exact: true }) });
  await form.getByRole('textbox', { name: 'Họ tên', exact: true }).fill('Phase9 Created Driver');
  await form.getByRole('textbox', { name: 'Email', exact: true }).fill('phase9-created@example.test');
  await form.getByRole('textbox', { name: 'Điện thoại', exact: true }).fill('0901234567');
  await form.getByLabel(/Mật khẩu khởi tạo/).fill(process.env.MINILOGISTICS_E2E_PASSWORD!);
  await form.getByRole('button', { name: 'Tạo người dùng', exact: true }).click();
  await expect(form.getByLabel(/Mật khẩu khởi tạo/)).toHaveValue('');
  await confirmAdmin(page, '/admin/users', 'POST');
  await page.getByRole('textbox', { name: 'Tìm kiếm', exact: true }).fill('phase9-created@example.test');
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await page.getByRole('button', { name: 'Sức chứa Phase9 Created Driver', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Giới hạn đơn active', exact: true }).fill('9');
  await page.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
  await confirmAdmin(page, '/capacity', 'PUT');
  await page.getByRole('button', { name: 'Vùng Phase9 Created Driver', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm vùng', exact: true }).click();
  await page.getByRole('combobox', { name: 'Hub', exact: true }).click();
  await page.getByTitle('MOBILE-TEST — Mobile Hub', { exact: true }).click();
  await page.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
  await confirmAdmin(page, '/working-areas', 'PUT');
  await page.getByRole('button', { name: 'Đổi mật khẩu Phase9 Created Driver', exact: true }).click();
  await page.getByLabel(/Mật khẩu mới/).fill(process.env.MINILOGISTICS_E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
  await confirmAdmin(page, '/password', 'PUT');
  await page.getByRole('button', { name: 'Đổi hoạt động Phase9 Created Driver', exact: true }).click();
  await confirmAdmin(page, '/active', 'PUT');
  await page.getByRole('link', { name: 'Shop', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Quản trị Shop', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Đổi hoạt động Phase9 Admin Shop', exact: true }).click();
  await confirmAdmin(page, '/active', 'PUT');
});
